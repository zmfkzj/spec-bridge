// LikeC4 adapter: official model API (LikeC4.fromWorkspace().computedModel()) - the semantic
// model, not rendered diagrams. Locations come from the language services (tool positions).
import { createRequire } from 'node:module'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import type { Constraint, SourceLocation, SourceVersion } from '../ir/types.ts'
import { REPO_ROOT, fileSha, packageVersion, rel } from '../util.ts'
import { type AdapterContext, type AdapterResult, emptyResult, entity, relation } from './common.ts'

const ADAPTER = 'likec4@1'
const require = createRequire(join(REPO_ROOT, 'package.json'))

/** Metadata keys SpecBridge reads (values: comma/space separated identifiers). */
export const C4_KEYS = {
  provides: 'specbridge_provides',            // element: operations/interfaces the element provides
  requirements: 'specbridge_requirements',    // element: requirement ids the element satisfies
  owns: 'specbridge_owns',                    // element: data types owned
  interface: 'specbridge_interface',          // element: TypeSpec interface it realises
  forbidden: 'specbridge_forbidden_dependencies', // element: elements it must not depend on
  operations: 'specbridge_operations',        // relation: operations invoked over this relation
}

const list = (v: unknown): string[] => (Array.isArray(v) ? v : typeof v === 'string' ? [v] : []).flatMap(s => String(s).split(/[\s,]+/)).filter(Boolean)

export async function extractLikeC4(rootRel: string, ctx: AdapterContext): Promise<AdapterResult> {
  const root = join(ctx.workspace, rootRel)
  const version = packageVersion('likec4')
  const res = emptyResult('likec4', version, rootRel, `likec4 ${version} LikeC4.fromWorkspace().computedModel() + languageServices.locate()`)
  res.source.lossy.push('Element/relation styling and view layout are ignored (presentation only)', 'Relation ids generated by LikeC4 are content hashes; SpecBridge uses source->target#n identities instead')
  const { LikeC4 } = await import(require.resolve('likec4'))
  let l: any
  try {
    l = await LikeC4.fromWorkspace(root, { printErrors: false, logger: false })
  } catch (e) {
    res.source.status = 'ERROR'
    res.source.diagnostics.push({ severity: 'error', message: 'LikeC4 workspace failed to load: ' + (e as Error).message })
    return res
  }
  for (const p of l.documentPaths() as string[]) res.source.files.push({ path: rel(ctx.workspace, p), sha256: fileSha(p) })
  for (const d of l.getErrors()) {
    res.source.status = 'ERROR'
    res.source.diagnostics.push({ severity: 'error', message: d.message, location: { file: rel(ctx.workspace, d.sourceFsPath), line: d.line + 1, locatedBy: 'tool' } })
  }
  for (const d of l.getWarnings?.() ?? []) res.source.diagnostics.push({ severity: 'warning', message: d.message, location: { file: rel(ctx.workspace, d.sourceFsPath), line: (d.line ?? 0) + 1, locatedBy: 'tool' } })
  if (res.source.status === 'ERROR') return res // an invalid model would yield unreliable semantics
  const model = await l.computedModel()
  const loc = (q: any): SourceLocation => {
    try {
      const r = l.languageServices.locate(q)
      if (r) return { file: rel(ctx.workspace, fileURLToPath(r.uri)), line: r.range.start.line + 1, column: r.range.start.character + 1, endLine: r.range.end.line + 1, locatedBy: 'tool' }
    } catch { /* fall through */ }
    return { file: rootRel }
  }
  const sv = (file: string): SourceVersion => ({ tool: 'likec4', toolVersion: version, fileSha256: res.source.files.find(f => f.path === file)?.sha256, gitRevision: ctx.git.revision, gitDirty: ctx.git.dirty })
  const validation = { status: 'tool-validated' as const, by: 'likec4 language services (0 errors)' }

  for (const e of model.elements()) {
    const md = e.$element.metadata ?? {}
    const id = `likec4:${e.id}`
    const source = loc({ element: e.id })
    const kind = String(e.kind)
    const type = /interface|api/i.test(kind) ? 'Interface' : 'Component'
    res.entities.push(entity({
      id, type, name: e.title, tool: 'likec4', source, version: sv(source.file), method: 'model-api', adapter: ADAPTER, validation,
      attrs: { fqn: e.id, kind, title: e.title, technology: e.technology ?? null, description: e.$element.description?.txt ?? e.$element.description?.md ?? null, tags: [...(e.tags ?? [])], metadata: md, parent: e.parent?.id ?? null },
    }))
    if (e.parent) res.relations.push(relation('CONTAINS', `likec4:${e.parent.id}`, id, 'Explicit', 'likec4.hierarchy', [{ kind: 'source', detail: `${e.parent.id} contains ${e.id}`, location: source }]))
    const mdLoc = (key: string) => { const p = loc({ element: e.id, property: `metadata.${key}` }); return p.line ? p : source }
    for (const op of list(md[C4_KEYS.provides])) res.refs.push({ from: id, ref: op, expect: ['operation', 'interface'], relation: 'EXPOSES', rule: `likec4.metadata.${C4_KEYS.provides}`, location: mdLoc(C4_KEYS.provides), tool: 'likec4', strict: true })
    for (const r of list(md[C4_KEYS.requirements])) res.refs.push({ from: id, ref: r, expect: ['requirement'], relation: 'SATISFIES', rule: `likec4.metadata.${C4_KEYS.requirements}`, location: mdLoc(C4_KEYS.requirements), tool: 'likec4', strict: true })
    for (const t of list(md[C4_KEYS.owns])) res.refs.push({ from: id, ref: t, expect: ['type'], relation: 'OWNS', rule: `likec4.metadata.${C4_KEYS.owns}`, location: mdLoc(C4_KEYS.owns), tool: 'likec4', strict: true })
    for (const t of list(md[C4_KEYS.interface])) res.refs.push({ from: id, ref: t, expect: ['interface'], relation: 'IMPLEMENTS', rule: `likec4.metadata.${C4_KEYS.interface}`, location: mdLoc(C4_KEYS.interface), tool: 'likec4', strict: true })
    for (const t of list(md[C4_KEYS.forbidden])) {
      const c: Constraint = {
        id: `constraint:${id}#C4-FORBIDDEN:${t}`, kind: 'DependencyRestriction', origin: id, tool: 'likec4', trust: 'Explicit', interpretation: 'structured',
        subject: { entity: id, direction: 'any' }, params: { target: t }, text: `${e.id} must not depend on ${t}`, source: mdLoc(C4_KEYS.forbidden),
        evidence: [{ kind: 'source', detail: `metadata ${C4_KEYS.forbidden} '${t}'`, location: mdLoc(C4_KEYS.forbidden) }],
      }
      res.constraints.push(c)
    }
  }
  const pairCount = new Map<string, number>()
  for (const r of model.relationships()) {
    const key = `${r.source.id}->${r.target.id}`
    const n = (pairCount.get(key) ?? 0) + 1
    pairCount.set(key, n)
    const source = loc({ relation: r.id })
    const md = r.$relationship.metadata ?? {}
    const from = `likec4:${r.source.id}`, to = `likec4:${r.target.id}`
    const rel0 = relation('DEPENDS_ON', from, to, 'Explicit', 'likec4.relationship', [{ kind: 'source', detail: `${key} '${r.title ?? ''}'`, location: source }], { kind: r.kind ?? null, title: r.title ?? null, technology: r.technology ?? null, metadata: md, index: n, likec4Id: r.id })
    if (n > 1) rel0.id += `#${n}`
    res.relations.push(rel0)
    for (const op of list(md[C4_KEYS.operations])) res.refs.push({ from, ref: op, expect: ['operation'], relation: 'CONSUMES', rule: `likec4.relationship.metadata.${C4_KEYS.operations}`, location: source, tool: 'likec4', strict: true, via: to })
  }
  for (const v of model.views()) {
    if (v.$view._type !== 'dynamic') continue
    const source = loc({ view: v.id })
    const steps = (v.$view.edges ?? []).map((e: any) => ({ source: e.source, target: e.target, title: e.label ?? null, backedByModelRelation: (e.relations ?? []).length > 0 }))
    const id = `likec4-flow:${v.id}`
    res.entities.push(entity({ id, type: 'Flow', name: v.title ?? v.id, tool: 'likec4', source, version: sv(source.file), method: 'model-api', adapter: ADAPTER, validation, attrs: { view: v.id, steps } }))
    for (const s of steps) for (const end of [s.source, s.target]) {
      if (!res.relations.some(r => r.type === 'REFERENCES' && r.from === id && r.to === `likec4:${end}`)) res.relations.push(relation('REFERENCES', id, `likec4:${end}`, 'Explicit', 'likec4.dynamic-view.step', [{ kind: 'source', detail: `dynamic view ${v.id}`, location: source }]))
    }
  }
  for (const d of model.deployment.elements()) {
    const id = `likec4-deploy:${d.id}`
    const source = loc({ deployment: d.id })
    const inst = d.isInstance?.()
    res.entities.push(entity({ id, type: 'DeploymentNode', name: d.title ?? d.id, tool: 'likec4', source, version: sv(source.file), method: 'model-api', adapter: ADAPTER, validation, attrs: { kind: inst ? 'instance' : String(d.kind), instanceOf: inst ? d.element.id : null, parent: d.parent?.id ?? null } }))
    if (inst) res.relations.push(relation('DEPLOYS', id, `likec4:${d.element.id}`, 'Explicit', 'likec4.deployment.instanceOf', [{ kind: 'source', detail: `${d.id} instanceOf ${d.element.id}`, location: source }]))
    else if (d.parent) res.relations.push(relation('CONTAINS', `likec4-deploy:${d.parent.id}`, id, 'Explicit', 'likec4.deployment.hierarchy', [{ kind: 'source', detail: `${d.parent.id} contains ${d.id}`, location: source }]))
  }
  return res
}
