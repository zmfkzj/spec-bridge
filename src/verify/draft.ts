// Alloy model DRAFT assistance (spec 9.2). Deterministic template generation from IR facts;
// drafts are written under .specbridge/drafts, carry the SPECBRIDGE-DRAFT marker and are refused
// as evidence by `verify formal` until a person reviews them, removes the marker, places them in
// formal/ and approves a VERIFIES mapping.
import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import type { SemanticIR } from '../ir/types.ts'
import { IR_DIR } from '../ir/build.ts'
import { alloyAvailable, alloyParse } from '../adapters/alloy.ts'
import { slug } from '../util.ts'

export const DRAFT_MARKER = 'SPECBRIDGE-DRAFT'

export function draftAlloyModel(ir: SemanticIR, workspace: string, requirementId: string) {
  const req = ir.entities.find(e => e.id === requirementId && e.type === 'Requirement')
  if (!req) throw new Error(`requirement ${requirementId} not found`)
  const cons = ir.constraints.filter(k => k.origin === req.id || k.origin.startsWith(req.id + '#'))
  const conceptIds = [...new Set(cons.map(k => k.subject.conceptKey).filter((x): x is string => !!x && x.startsWith('typespec:type:')))]
  const correspondence: Array<{ element: string; from: string }> = []
  const missing: string[] = []
  const lines = [
    `// ${DRAFT_MARKER}: generated by SpecBridge from ${req.id} ("${req.name}").`,
    '// NOT EVIDENCE. Review every line, complete facts/transitions, remove this marker, move the file',
    '// into formal/, add it to specbridge.yaml and approve a VERIFIES mapping before it can count.',
    `module ${slug(req.name).replace(/-/g, '_') || 'draft'}`, '',
  ]
  const states = new Map<string, unknown[]>()
  for (const cid of conceptIds) {
    const t = ir.entities.find(e => e.id === cid)!
    const fields = ir.entities.filter(e => e.type === 'Field' && e.attrs.model === cid)
    const decls: string[] = []
    for (const f of fields) {
      const vals = f.attrs.values as unknown[] | null
      if (vals && (f.attrs.type === 'literal-union' || f.attrs.type === 'enum')) { states.set(`${t.attrs.concept}_${f.attrs.field}`, vals); decls.push(`var ${f.attrs.field}: one ${t.attrs.concept}_${f.attrs.field}`) }
      else if (f.attrs.typeRef) decls.push(`var ${f.attrs.field}: ${f.attrs.optional ? 'lone' : 'one'} ${String(f.attrs.typeRef).split('.').pop()}`)
      else decls.push(`var ${f.attrs.field}: ${f.attrs.optional ? 'lone' : 'one'} Value  -- ${f.attrs.type} in contract`)
      correspondence.push({ element: `${t.attrs.concept}.${f.attrs.field}`, from: f.id })
    }
    lines.push(`sig ${t.attrs.concept} {`, ...decls.map((d, i) => { const [code, note] = d.split('  -- '); return `  ${code}${i < decls.length - 1 ? ',' : ''}${note ? '  // ' + note : ''}` }), '}')
    correspondence.push({ element: String(t.attrs.concept), from: cid })
  }
  for (const [name, vals] of states) {
    lines.push(`abstract sig ${name} {}`, `one sig ${vals.map(v => `${name}_${String(v).replace(/\W/g, '_')}`).join(', ')} extends ${name} {}`)
  }
  if (lines.some(l => l.includes(' Value'))) lines.push('sig Value {}')
  if (!states.size) missing.push('no state space: the contract has no enumerated status/state field for the constrained concepts')
  missing.push('no transitions: SpecBridge does not invent behaviour; add preds with primed relations for each operation')
  let n = 0
  for (const k of cons) {
    if (!k.subject.concept || !k.subject.field || !conceptIds.includes(k.subject.conceptKey ?? '')) continue
    const C = k.subject.concept, f = k.subject.field
    const stateField = [...states.keys()].find(s => s.startsWith(`${C}_`))
    const guard = k.subject.state && stateField ? `x.${stateField.slice(C.length + 1)} = ${stateField}_${k.subject.state} implies ` : k.subject.state ? `/* state '${k.subject.state}' has no Alloy counterpart */ ` : ''
    let body: string | null = null
    if (k.kind === 'Cardinality') body = `all x: ${C} | ${guard}${k.params.min === 1 && k.params.max === 1 ? 'one' : k.params.max === 1 ? 'lone' : k.params.min === 1 ? 'some' : 'no'} x.${f}`
    else if (k.kind === 'Required' && k.subject.direction !== 'request') body = `all x: ${C} | ${guard}some x.${f}`
    else if (k.kind === 'Exclusivity') body = `all disj a, b: ${C} | no a.${f} & b.${f}`
    if (!body) continue
    const an = `${slug(req.name).replace(/-/g, '_')}_${++n}`
    lines.push('', `// from ${k.id}: "${k.text}"`, `assert ${an} { always ${body} }`, `check ${an} for 3 but 4 steps`)
    correspondence.push({ element: `assert ${an}`, from: k.id })
  }
  if (!n) missing.push('no invariant: none of the requirement constraints is a cardinality/presence/exclusivity statement on a contract concept')
  const dir = join(workspace, IR_DIR, 'drafts')
  mkdirSync(dir, { recursive: true })
  const file = join(dir, `${slug(req.name)}.als`)
  writeFileSync(file, lines.join('\n') + '\n')
  let syntax: { ok: boolean; error?: string } = { ok: false, error: 'Alloy unavailable' }
  if (alloyAvailable().ok) { const d = alloyParse(file); syntax = d.ok ? { ok: true } : { ok: false, error: d.error } }
  const report = { requirement: req.id, draft: file, status: 'DRAFT (unapproved, excluded from evidence)', syntaxCheck: syntax, correspondence, missing, reviewPath: ['review draft', `remove ${DRAFT_MARKER} marker`, 'move to formal/ and list in specbridge.yaml alloy.models', `specbridge mapping approve --type VERIFIES --from alloy:formal/<file>#assert:<name> --to ${req.id} --by <reviewer>`] }
  writeFileSync(file.replace(/\.als$/, '.review.json'), JSON.stringify(report, null, 1))
  return report
}
